export type NewSmartTaskAssignment = InferInsertModel<typeof smartTaskAssignments>;

export type EmployeeStateSignal = InferSelectModel<typeof employeeStateSignals>;
export type NewEmployeeStateSignal = InferInsertModel<typeof employeeStateSignals>;

export type KpiProactiveAlert = InferSelectModel<typeof kpiProactiveAlerts>;
export type NewKpiProactiveAlert = InferInsertModel<typeof kpiProactiveAlerts>;

export type MotivationMoment = InferSelectModel<typeof motivationMoments>;
export type NewMotivationMoment = InferInsertModel<typeof motivationMoments>;

export type TechnicalAssistSession = InferSelectModel<typeof technicalAssistSessions>;
export type NewTechnicalAssistSession = InferInsertModel<typeof technicalAssistSessions>;
